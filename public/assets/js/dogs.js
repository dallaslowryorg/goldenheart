function esc(value=''){
  return String(value).replace(/[&<>'"]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;',"'":'&#39;','"':'&quot;'}[c]));
}

function safeDogImage(image=''){
  const value=String(image||'').trim();
  if(value.startsWith('/media/')) return esc(value);
  if(value.startsWith('/assets/images/dogs/')) return esc(value);
  const file=value.replace(/^.*[\/]/,'');
  return esc(`/assets/images/dogs/${file}`);
}

function safeDogFilter(value=''){
  const filter=String(value||'').trim();
  if(!filter) return 'none';
  return /^(?:none|(?:(?:saturate|brightness|contrast|grayscale|sepia|opacity)\([0-9.]+%?\)\s*)+)$/i.test(filter) ? filter : 'none';
}

function dogCard(dog){
  const chips=[dog.age, dog.sex, dog.group==='graduate'?dog.location:null].filter(Boolean);
  if(dog.veteranPlacement) chips.push('Veteran Placement');
  const statusClass=dog.group==='available'?'available':dog.group==='pending'?'pending':dog.group==='graduate'?'graduate':dog.group==='partner'?'partner':'matched';
  const badgeLabel={available:'Available',pending:'Pending',matched:'Matched',partner:'Partner Placement',graduate:'Graduate'}[dog.group] || dog.status || '';
  const stage=dog.group==='graduate' ? `${dog.year ? `${dog.year} ` : ''}Graduate` : dog.group==='matched' ? 'Matched / In Training / Transitioning' : '';
  const imageStyle=`--dog-filter:${safeDogFilter(dog.imageFilter)}`;
  const cardId=String(dog.slug || dog.name || 'dog').toLowerCase().replace(/[^a-z0-9]+/g,'-').replace(/^-+|-+$/g,'');
  const alt=`${dog.name || 'Golden Heart dog'}, Golden Heart service dog${dog.group==='graduate'?' graduate':''}`;
  return `<article class="dog-card group-${esc(dog.group||'')}${dog.veteranPlacement?' veteran-placement-card':''}" id="${esc(cardId)}">
    <div class="dog-photo"><img loading="lazy" decoding="async" fetchpriority="low" style="${esc(imageStyle)}" src="${safeDogImage(dog.image)}" alt="${esc(alt)}"></div>
    <div class="dog-card-body">
      <div class="dog-title-row"><h3>${esc(dog.name)}</h3><span class="status status-${esc(statusClass)}">${esc(badgeLabel)}</span></div>
      ${chips.length?`<div class="chips">${chips.map(x=>`<span${x==='Veteran Placement'?' class="veteran-placement-chip"':''}>${esc(x)}</span>`).join('')}</div>`:''}
      ${dog.handlerName?`<p class="dog-handler"><strong>Handler:</strong> ${esc(dog.handlerName)}</p>`:''}
      ${dog.progress || stage ? `<p class="dog-stage">${esc(dog.progress || stage)}</p>` : ''}
      ${dog.specialties?.length?`<p class="dog-specialties"><strong>Training focus:</strong> ${dog.specialties.map(esc).join(' • ')}</p>`:''}
      <p class="dog-blurb">${esc(dog.blurb || '')}</p>
    </div>
  </article>`;
}

function newestFirst(a,b){
  const aTime=Date.parse(a.createdAt || '') || 0;
  const bTime=Date.parse(b.createdAt || '') || 0;
  return bTime-aTime;
}

function sortDogDirectory(dogs, active, isDirectory){
  if(!isDirectory) return dogs;
  const list=[...dogs];
  if(active==='available') return list.sort(newestFirst);
  if(active!=='all') return list;
  return list.sort((a,b)=>{
    const aAvailable=a.group==='available';
    const bAvailable=b.group==='available';
    if(aAvailable!==bAvailable) return aAvailable ? -1 : 1;
    if(aAvailable && bAvailable) return newestFirst(a,b);
    return 0;
  });
}

function renderDogs(){
  const validFilters=['all','available','pending','matched','partner','graduate'];
  const hashFilter=window.location.hash.replace('#','');

  document.querySelectorAll('[data-dog-grid]').forEach(grid=>{
    const filters=[...document.querySelectorAll('[data-dog-filter]')];
    let active=grid.dataset.initialFilter || (validFilters.includes(hashFilter)?hashFilter:'all');
    const limit=Number(grid.dataset.limit||0);

    const draw=()=>{
      let dogs=window.GOLDEN_HEART_DOGS.filter(d=>active==='all'||d.group===active);
      dogs=sortDogDirectory(dogs,active,grid.dataset.initialFilter===undefined);
      if(limit>0) dogs=dogs.slice(0,limit);
      grid.innerHTML=dogs.map(dogCard).join('');
      filters.forEach(b=>{
        const selected=b.dataset.dogFilter===active;
        b.classList.toggle('active',selected);
        b.setAttribute('aria-pressed',String(selected));
      });
    };

    filters.forEach(btn=>btn.addEventListener('click',()=>{
      active=btn.dataset.dogFilter;
      if(grid.dataset.initialFilter===undefined){
        const nextHash=active==='all'?'':`#${active}`;
        history.replaceState(null,'',`${window.location.pathname}${nextHash}`);
      }
      draw();
    }));

    if(grid.dataset.initialFilter===undefined){
      window.addEventListener('hashchange',()=>{
        const next=window.location.hash.replace('#','');
        active=validFilters.includes(next)?next:'all';
        draw();
      });
    }

    draw();
  });

  const counts=window.GOLDEN_HEART_DOGS.reduce((a,d)=>{a[d.group]=(a[d.group]||0)+1;return a;},{all:window.GOLDEN_HEART_DOGS.length});
  document.querySelectorAll('[data-dog-filter]').forEach(btn=>{
    const key=btn.dataset.dogFilter;
    if(btn.dataset.counted==='true') return;
    const count=counts[key]||0;
    btn.insertAdjacentHTML('beforeend',` <span class="filter-count">${count}</span>`);
    btn.dataset.counted='true';
  });
  document.querySelectorAll('[data-dog-count]').forEach(el=>{
    el.textContent=counts[el.dataset.dogCount]||0;
  });
}

function renderVeteranPlacements(){
  const dogs=window.GOLDEN_HEART_DOGS.filter(d=>d.veteranPlacement);
  const partnerDogs=window.GOLDEN_HEART_DOGS.filter(d=>d.group==='partner');
  const counts=window.GOLDEN_HEART_PROGRAM_COUNTS;

  document.querySelectorAll('[data-veteran-dog-grid]').forEach(grid=>{
    grid.innerHTML=dogs.map(dogCard).join('');
  });
  document.querySelectorAll('[data-veteran-count]').forEach(el=>{
    const key=el.dataset.veteranCount;
    el.textContent=counts[key] ?? 0;
  });
  document.querySelectorAll('[data-veteran-public-count]').forEach(el=>{
    el.textContent=counts.veteranPublicProfiles ?? dogs.length;
  });
  document.querySelectorAll('[data-veteran-unprofiled-count]').forEach(el=>{
    el.textContent=counts.veteranUnprofiledPlacements ?? Math.max(0,(counts.veteranPlacements||0)-dogs.length);
  });
  document.querySelectorAll('[data-veteran-placement-note]').forEach(el=>{
    const total=Number(counts.veteranPlacements ?? dogs.length);
    const publicCount=Number(counts.veteranPublicProfiles ?? dogs.length);
    const unprofiled=Number(counts.veteranUnprofiledPlacements ?? Math.max(0,total-publicCount));
    const placementWord=total===1?'placement':'placements';
    const publicVerb=publicCount===1?'is':'are';
    const publicWord=publicCount===1?'profile is':'profiles are';
    if(unprofiled>0){
      const extraWord=unprofiled===1?'placement is':'placements are';
      el.innerHTML=`Golden Heart currently counts <strong>${total} confirmed veteran client ${placementWord}</strong>. <strong>${publicCount}</strong> public ${publicWord} represented in the roster above; <strong>${unprofiled}</strong> additional confirmed ${extraWord} included in the total without a public profile.`;
    }else{
      el.innerHTML=`Golden Heart currently counts <strong>${total} confirmed veteran client ${placementWord}</strong>. All <strong>${publicCount}</strong> public profiles ${publicVerb} represented in the roster above.`;
    }
  });
  document.querySelectorAll('[data-veteran-partner-strip]').forEach(strip=>{
    strip.innerHTML=partnerDogs.map(d=>`<span>${esc(d.name)}</span>`).join('');
  });
}

async function loadDogDirectory(){
  try{
    const response=await fetch('/api/dogs',{headers:{'Accept':'application/json'}});
    if(!response.ok) throw new Error(`Dog API returned ${response.status}`);
    const payload=await response.json();
    if(Array.isArray(payload.dogs)){
      window.GOLDEN_HEART_DOGS=payload.dogs;
    }
    if(payload.counts && typeof payload.counts==='object'){
      window.GOLDEN_HEART_PROGRAM_COUNTS={...window.GOLDEN_HEART_PROGRAM_COUNTS,...payload.counts};
    }
  }catch(err){
    console.warn('Using bundled dog roster because the live dog directory is unavailable.',err);
  }
  renderDogs();
  renderVeteranPlacements();
}

loadDogDirectory();
